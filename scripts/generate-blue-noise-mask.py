#!/usr/bin/env python3
"""Generate deterministic, tileable 64x64 Ulichney void-and-cluster ranks.

Build-time/development dependency only: numpy and scipy. The installed OBS
plugin embeds the generated 4096-byte R8 mask; no Python or scipy at runtime.
The mask is periodic: density measurements use Gaussian blur with wrap mode.
"""
from pathlib import Path
import numpy as np
from scipy.ndimage import gaussian_filter

SIZE = 64
COUNT = SIZE * SIZE
SEED = 271828
SIGMA = 1.5
INITIAL_DOTS = COUNT // 10


def density(dots: np.ndarray) -> np.ndarray:
    return gaussian_filter(dots.astype(np.float64), sigma=SIGMA, mode="wrap", truncate=3.0)


def cluster(dots: np.ndarray) -> int:
    field = density(dots).ravel()
    return int(np.argmax(np.where(dots.ravel(), field, -np.inf)))


def void(dots: np.ndarray) -> int:
    field = density(dots).ravel()
    return int(np.argmin(np.where(~dots.ravel(), field, np.inf)))


def generate() -> np.ndarray:
    rng = np.random.default_rng(SEED)
    dots = np.zeros(COUNT, dtype=bool)
    dots[rng.choice(COUNT, INITIAL_DOTS, replace=False)] = True
    dots = dots.reshape(SIZE, SIZE)

    # Initial prototype: move crowded dots into the emptiest locations.
    for _ in range(10000):
        packed = dots.ravel()
        crowded = cluster(dots)
        packed[crowded] = False
        empty = void(dots)
        if crowded == empty:
            packed[crowded] = True
            break
        packed[empty] = True
    else:
        raise RuntimeError("Void-and-cluster initialization failed to converge")

    prototype = dots.copy()
    ranks = np.full(COUNT, -1, dtype=np.int32)
    packed_ranks = ranks.ravel()

    # First phase: rank the original low-density dots from high to low.
    phase = prototype.copy()
    for rank in range(INITIAL_DOTS - 1, -1, -1):
        idx = cluster(phase)
        packed_ranks[idx] = rank
        phase.ravel()[idx] = False

    # Second phase: rank larger voids up to exactly half coverage.
    phase = prototype.copy()
    for rank in range(INITIAL_DOTS, COUNT // 2):
        idx = void(phase)
        packed_ranks[idx] = rank
        phase.ravel()[idx] = True

    # Third phase: invert the half-coverage pattern and remove its tightest
    # clusters, constructing the upper half ranks with complementary blue noise.
    phase = ~phase
    for rank in range(COUNT // 2, COUNT):
        idx = cluster(phase)
        packed_ranks[idx] = rank
        phase.ravel()[idx] = False

    assert np.array_equal(np.sort(ranks.ravel()), np.arange(COUNT))
    return (ranks.reshape(SIZE, SIZE).astype(np.uint32) * 256 // COUNT).astype(np.uint8)


def low_frequency_power(mask: np.ndarray, fill: float) -> float:
    binary = (mask.astype(np.float64) / 255.0 < fill).astype(float)
    spectrum = np.abs(np.fft.fftshift(np.fft.fft2(binary - binary.mean()))) ** 2
    yy, xx = np.mgrid[-SIZE // 2:SIZE // 2, -SIZE // 2:SIZE // 2]
    radius = np.sqrt(xx ** 2 + yy ** 2)
    # Low-frequency ring excludes the DC term.
    return float(spectrum[(radius > 0) & (radius <= 8)].mean())


def main() -> None:
    mask = generate()
    rng = np.random.default_rng(SEED)
    baseline = rng.permutation(np.repeat(np.arange(256, dtype=np.uint8), COUNT // 256)).reshape(SIZE, SIZE)

    for fill in (0.25, 0.5, 0.75):
        actual = low_frequency_power(mask, fill)
        white = low_frequency_power(baseline, fill)
        ratio = actual / white
        print(f"BLUE_NOISE_SPECTRUM fill={fill} low_power_ratio_vs_white={ratio:.4f}")
        # Genuine blue noise should strongly reduce low-frequency clumps.
        if ratio >= 0.65:
            raise RuntimeError(f"Mask has insufficient blue-noise suppression at {fill}: {ratio}")

    header = Path(__file__).resolve().parents[1] / "src/filters/blue-noise-mask.generated.h"
    lines = [
        "/* GENERATED by scripts/generate-blue-noise-mask.py; do not hand-edit.",
        " * Tileable 64x64 void-and-cluster mask, sigma 1.5, fixed seed 271828.",
        " * Rebuild using numpy/scipy; OBS does not require Python to run. */",
        "#pragma once",
        "#include <stdint.h>",
        "#define RETRO_BLUE_NOISE_SIZE 64",
        "static const uint8_t retro_blue_noise_r8[4096] = {",
    ]
    flat = mask.ravel().tolist()
    lines.extend("    " + ", ".join(str(int(v)) for v in flat[i:i + 16]) + "," for i in range(0, COUNT, 16))
    lines.append("};")
    header.write_text("\n".join(lines) + "\n")
    print(f"MASK_GENERATED bytes={mask.size} unique_levels={np.unique(mask).size} output={header}")


if __name__ == "__main__":
    main()
